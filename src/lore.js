/** 按一个整数种子取一条知识，保证同一局里顺序稳定但不重复得太快 */
export function factAt(seed) {
  const i = Math.abs(Math.floor(seed)) % MID_AUTUMN_FACTS.length;
  return MID_AUTUMN_FACTS[i];
}

/** 开局时给一句跟今天月相有关的话（用当前月龄挑） */
export function openerFor(phaseName) {
  const lore = loreFor(phaseName);
  if (lore) return `今晚的月亮是${phaseName}。${lore}`;
  return '今晚的月亮，和你手里这块月饼缺的那一口，是同一个形状。';
}

